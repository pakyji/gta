function mk(
  letter: string,
  title: string,
  summary: string,
  detail: string,
  difficulty: "easy" | "medium" | "hard",
  featured = false,
): GuideSeed {
  return {
    slug: `merge-${letter}-${title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 28)}`,
    category: "outfits",
    title: `Merge ${letter.toUpperCase()} — ${title}`,
    summary,
    body: [
      "## Goal",
      detail,
      "",
      "## Status",
      "**Unverified.** Outfit merge steps change with almost every title update.",
      "",
      "## Safety",
      "- Save 2–3 clean backup outfits first",
      "- No mod menus",
      "- If a slot bricks, replace it with a simple new outfit",
      "- Share platform + date in chat if you retest",
    ].join("\n"),
    status: "unverified",
    difficulty,
    platforms: ["ps4", "ps5"],
    featured,
    readMinutes: difficulty === "hard" ? 3 : 2,
    imageUrl: "/images/cat-outfits.jpg",
  };
}

